using System.Globalization;
using System.Text;
using FotoAutomat.Core;

namespace FotoAutomat.Infrastructure;

/// <summary>Writes Adobe/Resolve-style 3D .cube files. Numbers always use invariant culture.</summary>
public static class CubeLutFile
{
    public static string Format(CubeLut lut, string title)
    {
        lut.Validate();
        var text = new StringBuilder();
        var safeTitle = new string((title ?? "").Where(c => c != '"' && !char.IsControl(c)).ToArray()).Trim();
        text.Append("TITLE \"").Append(safeTitle.Length == 0 ? "FotoAutomat" : safeTitle).Append("\"\n");
        text.Append("# Generated by FotoAutomat from an editable colour recipe\n");
        text.Append("LUT_3D_SIZE ").Append(lut.Size.ToString(CultureInfo.InvariantCulture)).Append('\n');
        text.Append("DOMAIN_MIN ").AppendJoin(' ', lut.DomainMin.Select(Number)).Append('\n');
        text.Append("DOMAIN_MAX ").AppendJoin(' ', lut.DomainMax.Select(Number)).Append('\n');
        for (int i = 0; i < lut.Values.Length; i += 3)
            text.Append(Number(lut.Values[i])).Append(' ').Append(Number(lut.Values[i + 1])).Append(' ').Append(Number(lut.Values[i + 2])).Append('\n');
        return text.ToString();
    }

    public static void Save(string path, CubeLut lut, string title) => File.WriteAllText(path, Format(lut, title), new UTF8Encoding(false));

    private static string Number(double v) => v.ToString("0.000000", CultureInfo.InvariantCulture);
}
